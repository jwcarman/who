package org.jwcarman.who.examples.observability;

import org.springframework.beans.factory.InitializingBean;
import org.springframework.stereotype.Component;

import io.opentelemetry.api.OpenTelemetry;
import io.opentelemetry.instrumentation.logback.appender.v1_0.OpenTelemetryAppender;

/**
 * Connects the OpenTelemetry appender in {@code logback-spring.xml} to Spring Boot's OpenTelemetry,
 * as Spring Boot's documentation shows. Until it runs, the appender drops what it is given.
 */
@Component
class OpenTelemetryLogs implements InitializingBean {

  private final OpenTelemetry openTelemetry;

  OpenTelemetryLogs(OpenTelemetry openTelemetry) {
    this.openTelemetry = openTelemetry;
  }

  @Override
  public void afterPropertiesSet() {
    OpenTelemetryAppender.install(openTelemetry);
  }
}
