package org.jwcarman.who.examples.observability;

import static org.assertj.core.api.Assertions.assertThat;

import org.junit.jupiter.api.DisplayNameGeneration;
import org.junit.jupiter.api.DisplayNameGenerator;
import org.junit.jupiter.api.Test;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.context.ApplicationContext;
import org.springframework.security.core.userdetails.UserDetailsService;

/** who signs people in; Spring Boot's generated user and password are switched off. */
@DisplayNameGeneration(DisplayNameGenerator.ReplaceUnderscores.class)
class DefaultUserTest extends AbstractObservabilityTest {

  @Autowired ApplicationContext context;

  @Test
  void spring_boot_makes_no_user_of_its_own() {
    assertThat(context.getBeanNamesForType(UserDetailsService.class)).isEmpty();
  }
}
